import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const comicsRoot = join(root, 'src/assets/comics');
const webRoot = join(comicsRoot, 'web');
const manifestPath = join(root, 'src/app/home/comic-manifest.generated.ts');
const desktop = { width: 768, height: 1152 };
const mobile = { width: 480, height: 720 };
const bookends = ['cover', 'inside_left', 'inside_right', 'end', 'blank'];
const chapters = discoverChapters();
const optimizedImages = [];

if (chapters.length === 0) {
  throw new Error('No chapter folders containing comic pages were found.');
}

for (const chapter of chapters) {
  validateContinuousPages(chapter.folder, chapter.pageNumbers);

  for (const pageNumber of chapter.pageNumbers) {
    optimizedImages.push(
      [join(webRoot, 'desktop', chapter.folder, `page_${pageNumber}.webp`), desktop],
      [join(webRoot, 'mobile', chapter.folder, `page_${pageNumber}.webp`), mobile],
    );
  }
}

for (const name of bookends) {
  assertExists(join(comicsRoot, 'bookends', `${name}.png`));
  optimizedImages.push(
    [join(webRoot, 'desktop', 'bookends', `${name}-desktop.webp`), desktop],
    [join(webRoot, 'mobile', 'bookends', `${name}-mobile.webp`), mobile],
  );
}

const expectedManifest = createManifest(chapters);
const actualManifest = readFileSync(manifestPath, 'utf8');

if (actualManifest !== expectedManifest) {
  throw new Error(
    'Comic manifest is stale. Run `npm run optimize:pages` and commit the generated manifest.',
  );
}

await Promise.all(optimizedImages.map(([path, expected]) => validateImage(path, expected)));

const contentPageCount = chapters.reduce((total, chapter) => total + chapter.pageNumbers.length, 0);
console.log(`Comic assets verified: ${chapters.length} chapters, ${contentPageCount} content pages, ${optimizedImages.length} responsive images.`);

function discoverChapters() {
  return readdirSync(comicsRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && /^chapter\d+$/i.test(entry.name))
    .map(entry => {
      const folder = entry.name;
      const path = join(comicsRoot, folder);
      const pageNumbers = readdirSync(path)
        .map(file => file.match(/^page_(\d+)\.png$/i))
        .filter(Boolean)
        .map(match => Number(match[1]))
        .sort((a, b) => a - b);

      return {
        folder,
        number: Number(folder.match(/\d+/)?.[0] ?? 0),
        pageNumbers,
      };
    })
    .filter(chapter => chapter.pageNumbers.length > 0)
    .sort((a, b) => a.number - b.number);
}

function validateContinuousPages(folder, pageNumbers) {
  if (pageNumbers[0] !== 0) {
    throw new Error(`${folder} must start with page_0.png.`);
  }

  for (let index = 0; index < pageNumbers.length; index += 1) {
    if (pageNumbers[index] !== index) {
      throw new Error(`${folder} is missing page_${index}.png.`);
    }
  }
}

async function validateImage(path, expected) {
  assertExists(path);
  const metadata = await sharp(path).metadata();

  if (metadata.width !== expected.width || metadata.height !== expected.height) {
    throw new Error(
      `${path} is ${metadata.width}x${metadata.height}; expected ${expected.width}x${expected.height}.`,
    );
  }
}

function assertExists(path) {
  if (!existsSync(path)) {
    throw new Error(`Required comic asset is missing: ${path}`);
  }
}

function createManifest(chapterEntries) {
  const definitions = chapterEntries.map(chapter => [
    '  {',
    `    folder: '${chapter.folder}',`,
    `    title: 'Chapter ${chapter.number}',`,
    '    firstPage: 0,',
    `    lastPage: ${chapter.pageNumbers.at(-1)},`,
    `    pageCount: ${chapter.pageNumbers.length},`,
    '  },',
  ].join('\n'));

  return `// Generated by scripts/optimize-comic-pages.mjs. Do not edit manually.
export interface ComicChapterDefinition {
  folder: string;
  title: string;
  firstPage: number;
  lastPage: number;
  pageCount: number;
}

export const COMIC_CHAPTERS: readonly ComicChapterDefinition[] = [
${definitions.join('\n')}
];
`;
}
